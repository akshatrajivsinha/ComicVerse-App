export const getDistanceBetweenScreenPoints = (
  first: { x: number; y: number },
  second: { x: number; y: number },
) => {
  const dx = first.x - second.x;
  const dy = first.y - second.y;
  return Math.sqrt(dx * dx + dy * dy);
};

